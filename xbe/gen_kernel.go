//go:build ignore

// gen_kernel turns nxdk's xboxkrnl.exe.def (CC0) into kernel_table.go.
// Run with: go generate ./xbe
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"strconv"
)

var line = regexp.MustCompile(`^\s+(@?)([A-Za-z_][A-Za-z0-9_]*)(?:@([0-9]+))?\s+@\s*([0-9]+)\s+NONAME(\s+DATA)?\s*$`)

func main() {
	f, err := os.Open("xboxkrnl.exe.def")
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()

	var b bytes.Buffer
	b.WriteString("// Code generated by gen_kernel.go from xboxkrnl.exe.def; DO NOT EDIT.\n\n")
	b.WriteString("package xbe\n\n")
	b.WriteString("var kernelExports = map[uint32]KernelExport{\n")
	n := 0
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		m := line.FindStringSubmatch(sc.Text())
		if m == nil {
			continue
		}
		ord, _ := strconv.Atoi(m[4])
		argBytes, _ := strconv.Atoi(m[3])
		conv := "Stdcall"
		switch {
		case m[5] != "":
			conv = "Data"
		case m[1] == "@":
			conv = "Fastcall"
		case m[3] == "":
			conv = "Cdecl"
		}
		fmt.Fprintf(&b, "\t%d: {Ordinal: %d, Name: %q, Conv: %s, ArgBytes: %d},\n", ord, ord, m[2], conv, argBytes)
		n++
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("kernel_table.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote %d kernel exports", n)
}
